MCP_HELP = r"""MCP: С НУЛЯ ДО ПЕРВОГО ПОДКЛЮЧЕНИЯ

MCP даёт модели инструменты внешнего сервиса или локальной программы.
Например, GitHub MCP умеет читать файлы репозитория. Обычно вы подключаете
готовый MCP-сервер по инструкции его автора, а не пишете сервер сами.
JSON лишь описывает подключение: произвольный сайт/скрипт не становится MCP.
Настройка ниже не требует платной генерации; сам сервис может иметь тарифы.

1. ВЫБЕРИТЕ СПОСОБ ПОДКЛЮЧЕНИЯ
HTTP: автор предоставляет конечный URL MCP; отдельный процесс не нужен.
stdio: MCP-программа работает на вашем компьютере; сначала установите её
и нужный runtime (например, Node/Python) по инструкции автора.
Обычная команда терминала не заменяет MCP-программу.
В обоих режимах CLI MCP-клиент работает на вашем компьютере.
Полная exe/Linux-сборка уже содержит SDK. Для облегчённой установки из
исходников: python -m pip install -r client/requirements-mcp.txt
Эту команду запускают из папки исходников в терминале, не как сообщение ИИ.

2. СОЗДАЙТЕ mcp.json
Откройте домашнюю папку пользователя и приватный каталог CLI:
Linux: ~/.gemini_cli/mcp.json
Windows: %USERPROFILE%\.gemini_cli\mcp.json
В проводнике Windows вставьте %USERPROFILE% в адресную строку.
Создайте .gemini_cli при необходимости. Сохраните mcp.json как UTF-8,
не mcp.json.txt. Конфиги из рабочей папки проекта не подключаются.

Пример готового HTTP-подключения: официальный GitHub MCP, только чтение.
Он использует публичный адрес сервиса, а не данные вашего окружения:
{
  "version": 1,
  "servers": [
    {
      "name": "github",
      "transport": "http",
      "url": "https://api.githubcopilot.com/mcp/x/repos/readonly",
      "auth": "bearer",
      "tools": ["get_file_contents"],
      "timeout": 30
    }
  ]
}
name — короткое локальное имя для команд /mcp. tools — исходные имена
нужных инструментов, timeout — время ожидания в секундах.
В JSON двойные кавычки, без комментариев и лишней запятой в конце.
Несколько подключений — несколько объектов в servers через запятую.
После изменения mcp.json перезапустите CLI. Чтение файла ничего не запускает.

3. ВОЙДИТЕ В СЕРВИС
Для примера GitHub создайте персональный токен в настройках GitHub:
Settings → Developer settings → Personal access tokens. Для первого теста
выберите публичные репозитории, короткий срок, без прав записи.
Затем в Gemini CLI:
  /mcp login github memory
Введите токен только в появившееся поле со звёздочками.
НЕ вставляйте его в чат, mcp.json, URL, командную строку или репозиторий.
memory хранит секрет до выхода. keyring вместо memory — хранилище ОС;
оно должно быть доступно, автоматического сохранения в файл нет.
У сервиса без авторизации login не нужен; для OAuth следуйте инструкции
его автора и поддерживаемому CLI потоку. Вход в Remote CLI и в MCP независимы.

4. ПРОВЕРЬТЕ, ВКЛЮЧИТЕ И ИСПОЛЬЗУЙТЕ
  /mcp                      — состояние подключений
  /mcp check github         — соединиться и обновить каталог
  /mcp tools github         — увидеть доступные инструменты и причины отказа
  /mcp enable github        — разрешить модели выбранный набор
login/check не включают инструменты для модели автоматически.
Теперь обычным сообщением попросите: «Через GitHub MCP прочитай LICENSE
публичного репозитория github/github-mcp-server; только чтение».
Перед y проверьте имя сервиса, инструмент get_file_contents и аргументы.
Вызов может отправлять данные сервису; результат передаётся модели.
Каждый вызов требует подтверждения. /undo не откатывает внешние действия.
Tab дополняет действия и имена. В Remote нужны поддержка MCP на сервере
и доступная возможность MCP в подписке; Local серверной подписки не требует.

5. ЕСЛИ НУЖЕН ЛОКАЛЬНЫЙ stdio
В servers добавляют запись вида:
  {"name":"example","transport":"stdio","command":"node",
   "args":["/opt/example-mcp/server.js"],"tools":["example_tool"]}
Это ШАБЛОН, не готовый сервер: замените программу, вымышленный путь и
имена tools по документации установленного MCP. Windows-пример пути:
C:/Tools/example-mcp/server.js. command — исполняемый файл, args — отдельные
аргументы; используйте реальный node.exe/python, не оболочку или npx.cmd.
Если автор требует env, env_keys содержит только имена переменных;
значения вводятся через /mcp login example memory. Не записывайте секреты
в args. Сервер запускается при login/check/enable, не при обнаружении.
Для собственного сервера нужен MCP SDK и реализация протокола:
https://modelcontextprotocol.io/docs/develop/build-server

6. ОШИБКИ И УДАЛЕНИЕ
Нет подключений: проверьте имя/место mcp.json и массив servers.
После правки перезапустите CLI. Действие не выполнено: проверьте установку,
конечный HTTPS URL, доступность сервиса и вход; затем /mcp tools имя.
Не отключайте TLS. 401/403 у сервиса — проверьте вход/права; 429 — подождите.
Лимиты CLI: до 8 подключений, 16 объявленных tools суммарно. При большом
каталоге оставьте небольшой tools; неподдерживаемые схемы видны с причиной.
  /mcp disable github       — отключить инструменты и соединение
  /mcp logout github        — удалить локальные credentials
Затем удалите объект из servers и перезапустите CLI. Токен отзывается
отдельно в настройках сервиса. Клиент не запрашивает пароль вашего GitHub.
Источник примера: https://github.com/github/github-mcp-server/blob/main/docs/remote-server.md
"""


