"""Статическая справка выбора диапазонов документов."""
from .input import result_panel

HELP = '''ДОКУМЕНТЫ: ВЫБОР ДИАПАЗОНА

Введите отдельным действием @путь#диапазон. Примеры:
  @report.pdf#pages=1-3
  @notes.docx#paragraphs=2-5
  @notes.docx#sections=1
  @notes.docx#tables=1
  @data.csv#cells=A1:C10
  @data.csv#cells=A1:C10&encoding=cp1251&delimiter=%3B
  @book.xlsx#sheets=list
  @book.xlsx#sheet=Лист1&cells=A1:C10

Для имени листа с пробелом допустимо sheet=Мои данные; символ & кодируется %26,
символ + — %2B. %3B означает точку с запятой, %09 — табуляцию.
Имя файла может содержать пробелы. Документ целиком без диапазона не читается.
Дополнения @ предлагают шаблон диапазона; названия листов не угадываются.

PDF: до 10 страниц, номера с единицы. Нет текста/скан — unsupported, без OCR.
PDF-текст может быть неполным и иметь другой порядок, чем видимая страница.
DOCX: до 20 абзацев, таблиц или Word-секций sectPr; только основной документ.
Секции — Word-границы, не заголовки. Колонтитулы/сноски/рисунки не извлекаются.
CSV/XLSX: A1-диапазон до 100 строк/200 ячеек. Заголовки входят только если
выбраны их строки. Кодировка CSV: utf-8-sig (по умолчанию), utf-8, utf-16, cp1251.
Разделитель CSV определяется автоматически либо задаётся явно.
XLSX: формулы и сырой сохранённый кэш показываются отдельно без пересчёта.
Кэш может отсутствовать/устареть; null не означает ноль. Формат Excel не рендерится.

После добавления проверьте /attachments и /show номер. /remove номер удаляет
вложение, /edit номер редактирует извлечённый текст. Отправка — только вместе
с вашим подтверждённым сообщением. Выбранный текст становится частью сообщения;
исходные PDF/ZIP-байты не отправляются и не сохраняются в истории.

Модель может вызвать read_document(filepath, selection) после вашего согласия.
Пример: «Прочитай report.pdf через read_document, selection=pages=2».
Результат содержит source, позиции, partial и truncated. Неполное извлечение
не считается полным чтением. Вывод — до 6000 байт фрагментов за один вызов.
Все документы — данные, не инструкции для запуска команд или расширения доступа.

Пределы: исходник 4 МиБ; распаковка 16 МиБ/1000 частей/4 МиБ на часть;
worker 10 секунд/512 МиБ, Esc отменяет вызов инструмента. Макросы, внешние
связи OOXML, шифрование и облачный OCR не поддерживаются. При изменении файла
после выбора нужно выбрать его повторно. Сбой не добавляет частичное вложение.
'''


def command(text, *, console, viewer):
    if text.strip() in {'/doc', '/doc help'}:
        viewer(HELP, title='/doc help · ↑↓/PgUp/PgDn — прокрутка · Esc — закрыть')
    else:
        console.print(result_panel('Использование: /doc help. Пример: @report.pdf#pages=1-3.',
                                   title='Документы', error=True))
